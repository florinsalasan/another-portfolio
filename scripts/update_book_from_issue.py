#!/usr/bin/env python3
"""
Updates or adds a book entry in `content/bookshelf/books.toml` from either:
  1. A GitHub Issue Form body (passed via the `ISSUE_BODY` environment variable), or
  2. Command-line flags (useful for local scripts or a Discord bot).

Usage:
  ISSUE_BODY="..." python3 scripts/update_book_from_issue.py
  python3 scripts/update_book_from_issue.py --title "East of Eden" --rating 5 --review "Masterpiece."
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tomllib
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
BOOKS_TOML = ROOT_DIR / "content" / "bookshelf" / "books.toml"


def toml_escape_str(val: str) -> str:
    return val.replace("\\", "\\\\").replace('"', '\\"')


def parse_issue_form(body: str) -> dict[str, str]:
    """
    Parses the markdown generated by `.github/ISSUE_TEMPLATE/book.yml`.
    Sections look like:
      ### Field Label

      Field value
    """
    sections: dict[str, str] = {}
    parts = re.split(r"^###\s+(.+?)\s*$", body.strip(), flags=re.MULTILINE)
    # parts[0] is text before first ###; then pairs of (heading, content)
    for i in range(1, len(parts) - 1, 2):
        heading = parts[i].strip().lower()
        content = parts[i + 1].strip()
        if content == "_No response_":
            content = ""
        sections[heading] = content

    return {
        "title": sections.get("book title", ""),
        "author": sections.get("author", ""),
        "status": sections.get("reading status", ""),
        "rating": sections.get("rating", ""),
        "date_read": sections.get("date read", ""),
        "isbn": sections.get("isbn (optional)", ""),
        "tags": sections.get("tags (optional)", ""),
        "summary": sections.get("short summary (optional)", ""),
        "review": sections.get("review & notes (optional)", ""),
    }


def upsert_field_in_block(block: str, key: str, formatted_value: str) -> str:
    pattern = re.compile(rf"^{re.escape(key)}\s*=\s*.*$", flags=re.MULTILINE)
    replacement = f"{key} = {formatted_value}"
    if pattern.search(block):
        return pattern.sub(lambda _: replacement, block, count=1)

    # Insert before `review =` or `summary =` if present, otherwise at end of block
    for anchor in ("summary", "review"):
        anchor_pat = re.compile(rf"^({anchor}\s*=)", flags=re.MULTILINE)
        if anchor_pat.search(block):
            return anchor_pat.sub(lambda m: f"{replacement}\n{m.group(1)}", block, count=1)

    return block.rstrip() + f"\n{replacement}\n\n"


def update_review_in_block(block: str, review_text: str) -> str:
    formatted = f'review = """\n{review_text.strip()}\n"""'
    multiline_pat = re.compile(r'^review\s*=\s*""".*?"""', flags=re.MULTILINE | re.DOTALL)
    singleline_pat = re.compile(r'^review\s*=\s*"[^"]*"', flags=re.MULTILINE)

    if multiline_pat.search(block):
        return multiline_pat.sub(lambda _: formatted, block, count=1)
    if singleline_pat.search(block):
        return singleline_pat.sub(lambda _: formatted, block, count=1)
    return block.rstrip() + f"\n{formatted}\n"


def build_new_block(fields: dict) -> str:
    title = toml_escape_str(fields["title"])
    author = toml_escape_str(fields.get("author") or "Unknown Author")
    status = fields.get("status")
    if not status or status == "(Keep Existing)":
        status = "Finished"

    rating_raw = fields.get("rating", "")
    rating = int(rating_raw) if rating_raw.isdigit() else 0
    date_read = toml_escape_str(fields.get("date_read", ""))
    isbn = toml_escape_str(fields.get("isbn", ""))
    summary = toml_escape_str(fields.get("summary", ""))
    review = fields.get("review", "").strip()

    tags_raw = fields.get("tags", "")
    tag_items = [f'"{toml_escape_str(t.strip())}"' for t in tags_raw.split(",") if t.strip()]
    tags_toml = f"[{', '.join(tag_items)}]"

    lines = [
        "[[books]]",
        f'title = "{title}"',
        f'author = "{author}"',
        f'status = "{toml_escape_str(status)}"',
    ]
    if date_read:
        lines.append(f'date_read = "{date_read}"')
    lines.append(f"rating = {rating}")
    if isbn:
        lines.append(f'isbn = "{isbn}"')
    lines.append(f"tags = {tags_toml}")
    lines.append(f'summary = "{summary}"')
    if review:
        lines.append(f'review = """\n{review}\n"""')
    else:
        lines.append('review = """\n\n"""')

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Add or update a book in books.toml")
    parser.add_argument("--title", help="Book title")
    parser.add_argument("--author", help="Book author")
    parser.add_argument("--status", help="Finished | Reading | Want to Read")
    parser.add_argument("--rating", help="Rating 0-5")
    parser.add_argument("--date-read", dest="date_read", help="Date read (e.g. Nov 2026)")
    parser.add_argument("--isbn", help="Optional ISBN override")
    parser.add_argument("--tags", help="Comma-separated tags")
    parser.add_argument("--summary", help="Short one-line summary")
    parser.add_argument("--review", help="Markdown review/notes")
    args = parser.parse_args()

    issue_body = os.environ.get("ISSUE_BODY", "").strip()
    if issue_body:
        fields = parse_issue_form(issue_body)
    else:
        fields = {
            "title": args.title or "",
            "author": args.author or "",
            "status": args.status or "",
            "rating": args.rating or "",
            "date_read": args.date_read or "",
            "isbn": args.isbn or "",
            "tags": args.tags or "",
            "summary": args.summary or "",
            "review": args.review or "",
        }

    title = fields.get("title", "").strip()
    if not title:
        print("Error: Book title is required.", file=sys.stderr)
        return 1

    if not BOOKS_TOML.exists():
        print(f"Error: {BOOKS_TOML} not found.", file=sys.stderr)
        return 1

    raw_toml = BOOKS_TOML.read_text(encoding="utf-8")
    parsed = tomllib.loads(raw_toml)
    existing_books = parsed.get("books", [])

    # Check if book already exists (case-insensitive title match)
    matched_title = None
    for b in existing_books:
        if b.get("title", "").strip().lower() == title.lower():
            matched_title = b.get("title", "").strip()
            break

    if matched_title:
        blocks = re.split(r"(?=^\[\[books\]\])", raw_toml, flags=re.MULTILINE)
        title_pat = re.compile(
            r'^title\s*=\s*"' + re.escape(matched_title) + r'"', flags=re.MULTILINE
        )
        updated_blocks = []
        for block in blocks:
            if not block.startswith("[[books]]") or not title_pat.search(block):
                updated_blocks.append(block)
                continue

            if fields.get("author"):
                block = upsert_field_in_block(
                    block, "author", f'"{toml_escape_str(fields["author"])}"'
                )
            if fields.get("status") and fields["status"] != "(Keep Existing)":
                block = upsert_field_in_block(
                    block, "status", f'"{toml_escape_str(fields["status"])}"'
                )
            if fields.get("rating") and fields["rating"].isdigit():
                block = upsert_field_in_block(block, "rating", fields["rating"])
            if fields.get("date_read"):
                block = upsert_field_in_block(
                    block, "date_read", f'"{toml_escape_str(fields["date_read"])}"'
                )
            if fields.get("isbn"):
                clean_isbn = re.sub(r"[^0-9X]", "", fields["isbn"].upper())
                block = upsert_field_in_block(block, "isbn", f'"{clean_isbn}"')
                # Remove existing cover line so fetch_covers.py downloads the new ISBN's cover
                block = re.sub(r'^cover\s*=\s*"[^"]*"\n?', "", block, flags=re.MULTILINE)
            if fields.get("tags"):
                tag_items = [
                    f'"{toml_escape_str(t.strip())}"'
                    for t in fields["tags"].split(",")
                    if t.strip()
                ]
                block = upsert_field_in_block(block, "tags", f"[{', '.join(tag_items)}]")
            if fields.get("summary"):
                block = upsert_field_in_block(
                    block, "summary", f'"{toml_escape_str(fields["summary"])}"'
                )
            if fields.get("review"):
                block = update_review_in_block(block, fields["review"])

            updated_blocks.append(block)

        new_toml = "".join(updated_blocks)
        BOOKS_TOML.write_text(new_toml, encoding="utf-8")
        print(f"[✓] Updated existing book '{matched_title}' in books.toml")
    else:
        new_block = build_new_block(fields)
        new_toml = raw_toml.rstrip() + "\n\n" + new_block
        BOOKS_TOML.write_text(new_toml, encoding="utf-8")
        print(f"[✓] Added new book '{title}' to books.toml")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
